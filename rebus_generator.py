def _format_rebus(index: int) -> dict:
    puzzle = REBUS_PUZZLES[index % len(REBUS_PUZZLES)]
    return {
        "title": "Daily Rebus",
        "puzzle_number": index + 1,
        "category": puzzle["category"],
        "hint": puzzle["hint"],
        "answer": puzzle["answer"],
        "texts": puzzle["texts"],
        "lines": puzzle["lines"],
        "rects": puzzle["rects"],
    }


def generate_daily_rebus(target_date: date | None = None) -> dict:
    d = target_date or date.today()
    idx = d.toordinal() % len(REBUS_PUZZLES)
    yesterday_idx = (d - timedelta(days=1)).toordinal() % len(REBUS_PUZZLES)

    puzzle = _format_rebus(idx)
    yesterday = _format_rebus(yesterday_idx)
    puzzle["date"] = d.strftime("%b %d, %Y").upper()
    puzzle["yesterday_answer"] = yesterday["answer"]
    puzzle["yesterday_category"] = yesterday["category"]
    return puzzle
