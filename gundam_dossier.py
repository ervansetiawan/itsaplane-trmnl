@gundam_dossier_bp.route("/gundam/random", methods=["GET"])
@gundam_dossier_bp.route("/gundam/daily", methods=["GET"])
def gundam_dossier():
    """Returns a Gundam character dossier (random by default, or ?mode=daily / ?index=)."""
    mode = (request.args.get("mode") or "random").strip().lower()
    idx = request.args.get("index")
    if idx is not None and idx.isdigit():
        char = CHARACTERS[int(idx) % len(CHARACTERS)]
    elif mode == "daily":
        char = CHARACTERS[date.today().toordinal() % len(CHARACTERS)]
    else:
        char = random.choice(CHARACTERS)

    return jsonify(
        {
            "title": "Gundam Dossier",
            "name": char["name"],
            "native": char["native"],
            "image_url": char["image_url"],
            "timeline": char["timeline"],
            "faction": char["faction"],
            "series": char["series"],
            "medium": char["medium"],
            "mobile_suit": char["mobile_suit"],
            "quote": char["quote"],
            "bio": char["bio"],
            "date": datetime.now(timezone.utc).strftime("%b %d, %Y"),
        }
    )
