def fetch_random_retro_game(seed: int | None = None) -> dict:
    """Returns a random retro game screenshot and metadata payload."""
    rng = random.Random(seed) if seed is not None else random
    game = rng.choice(RETRO_GAMES)
    yr = game["year"]
    timeline_x = round(10 + max(0, min(25, yr - 1980)) / 25.0 * 180)
    return {
        "title": "Retro Game Showcase",
        "date": date.today().strftime("%b %d, %Y").upper(),
        "total_games": len(RETRO_GAMES),
        "timeline_x": timeline_x,
        **game,
    }
