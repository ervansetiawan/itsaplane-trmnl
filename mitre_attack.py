def generate_daily_mitre(today: date | None = None) -> dict:
    """Returns today's deterministic MITRE ATT&CK Enterprise technique."""
    d = today or date.today()
    tech = TECHNIQUES[d.toordinal() % len(TECHNIQUES)]
    tactic_idx = tech["tactic_index"]
    tactics = [
        {**t, "active": t["index"] == tactic_idx}
        for t in TACTICS
    ]

    return {
        "title": "MITRE ATT&CK Daily",
        "date": d.strftime("%b %d, %Y").upper(),
        "total_techniques": len(TECHNIQUES),
        "tactics": tactics,
        "technique_id": tech["technique_id"],
        "name": tech["name"],
        "tactic": tech["tactic"],
        "tactic_index": tactic_idx,
        "platforms": tech["platforms"],
        "data_sources": tech["data_sources"],
        "description": tech["description"],
        "detection": tech["detection"],
        "mitigation": tech["mitigation"],
        "url": f"https://attack.mitre.org/techniques/{tech['technique_id']}/",
    }
