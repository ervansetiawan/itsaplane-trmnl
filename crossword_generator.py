def generate_daily_puzzle(target_date: date | None = None) -> dict:
    d = target_date or date.today()
    puzzle = _build_puzzle_from_seed(d.toordinal())
    yesterday = _build_puzzle_from_seed((d - timedelta(days=1)).toordinal())
    puzzle["date"] = d.strftime("%b %d, %Y").upper()
    puzzle["yesterday_grid"] = yesterday["grid"]
    return puzzle
